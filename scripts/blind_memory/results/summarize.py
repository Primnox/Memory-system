"""Rebuild RESULTS.md from the saved --json outputs of bench_memory_blind.py."""
import json, math
from pathlib import Path

HERE = Path(__file__).parent
NAMES = {
    "old": "before (89ae45f)", "v3": "exp/memory-v3", "v4": "exp/memory-v4 (embeddings on)",
    "final": "fix/memory-change-detection", "mem-change": "fix/memory-change-detection",
    "mem-time": "fix/memory-time-phrases", "mem-verify": "exp/memory-change-verify (verifier on)",
    "new": "exp/memory-v3", "notopics": "exp/memory-v3, topic lexicon off", "safety": "fix/memory-safety",
    "lifecycle": "fix/memory-lifecycle", "scale": "perf/memory-scale", "robust": "fix/memory-robustness (not merged)",
    "emb": "exp/memory-embeddings", "v4_off": "exp/memory-v4 (embeddings off)", "v4_emb": "exp/memory-v4 (embeddings on)",
    "change": "fix/memory-change-detection",
}

def wilson(k, n):
    if not n:
        return "n/a"
    z = 1.96; p = k / n; c = (p + z * z / (2 * n)) / (1 + z * z / n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return f"{100 * p:.1f}% [{100 * (c - h):.0f}–{100 * (c + h):.0f}]"

def label(stem):
    for key in sorted(NAMES, key=len, reverse=True):
        if stem == key or stem.startswith(key + "_"):
            return NAMES[key]
    return stem

def row(path):
    d = json.loads(path.read_text(encoding="utf-8"))
    qs = d["qs"]; ans = [q for q in qs if q["type"] != "absent"]
    by = lambda t: [q for q in qs if q["type"] == t]
    sup = d["sup"].values()
    t, p, c = (sum(s[k] for s in sup) for k in ("true", "predicted", "correct"))
    cfg = d["config"].replace("split=", "")
    return (f"| `{path.stem}` | {label(path.stem)} | {cfg} | {sum(q['top1'] for q in ans)}/{len(ans)} = {wilson(sum(q['top1'] for q in ans), len(ans))} "
            f"| {sum(q['top1'] for q in by('current'))}/{len(by('current'))} | {sum(q['top1'] for q in by('past'))}/{len(by('past'))} "
            f"| {sum(q['top1'] for q in by('multi'))}/{len(by('multi'))} | {c}/{t} | {p - c} of {p} |")

out = ["# Blind memory results", "",
       "Generated by `summarize.py` from the `--json` outputs in `test_v1/` (first blind set, used to pick winners) and "
       "`test_v2/` (fresh set, written after tuning). Top-1 = first search result is a right answer; 95% Wilson intervals. "
       "Supersession = (old, successor) pairs noticed; mistaken = retirements not matching a true pair. "
       "`oracle` = true date supplied; `model` = the local 9B writes query and date. Per-question files hold only ids and booleans.", ""]
for split in ("test_v2", "test_v1"):
    out += [f"## {split}", "", "| file | version | config | answerable top-1 | now | past | multi | changes noticed | mistaken retirements |",
            "|---|---|---|---|---|---|---|---|---|"]
    out += [row(p) for p in sorted((HERE / split).glob("*.json"))]
    out.append("")
(HERE / "RESULTS.md").write_text("\n".join(out), encoding="utf-8")
print("\n".join(out[:12]))
